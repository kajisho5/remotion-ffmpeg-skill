#!/usr/bin/env python3
"""Generate references/scripts.md from the contract (internal; not a tool).

    python3 scripts/_docs.py           # rewrite references/scripts.md
    python3 scripts/_docs.py --check   # exit 1 if it is out of date (tests run this)

The reference is generated, never edited by hand, so it cannot drift from the scripts' own parsers.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import _contract  # noqa: E402

OUT = HERE.parent / "references" / "scripts.md"


def render() -> str:
    c = _contract.build()
    lines = [
        "# Script reference",
        "",
        "<!-- Generated by scripts/_docs.py from scripts/_contract.py. Do not edit by hand. -->",
        "",
        # No package version here: a version bump must not make the generated reference stale.
        f"Contract {c['contract_version']} · timeline schema `{c['timeline_schema']}`.",
        "Every script also takes `--json`, `--dry-run`, `--overwrite` and `--timeout SECONDS`.",
        "Exit codes: " + ", ".join(f"{k} = {v}" for k, v in c["conventions"]["errors"].items()) + ".",
        "",
    ]
    for t in c["tools"]:
        s = t["inputSchema"]
        lines += [f"## {t['name']}.py", "", t["summary"], "",
                  f"- Role: {t['role']} — {c['roles'][t['role']]}",
                  f"- Writes: {t['writes'] or 'nothing'}",
                  f"- Verifies: {t['verification']}",
                  f"- ffmpeg-skill: {', '.join(t['ffmpeg_skill']) or '—'}",
                  f"- `--dry-run`: {'plans without writing' if t['dry_run'] else 'not applicable (reports only)'}",
                  "", "| Argument | Type | Default | Meaning |", "|---|---|---|---|"]
        for name, p in s["properties"].items():
            if name in ("dry_run", "overwrite", "timeout"):
                continue
            arg = name if name in s["x-positional"] else t["flags"].get(name, "--" + name.replace("_", "-"))
            if name in s["required"] and name not in s["x-positional"]:
                arg += " (required)"
            typ = p.get("type", "")
            if typ == "array":
                typ = f"{p['items'].get('type', '')}, repeatable"
            if "enum" in p or ("items" in p and "enum" in p["items"]):
                typ += ": " + " / ".join(map(str, p.get("enum") or p["items"]["enum"]))
            default = f"`{p['default']}`" if "default" in p else ""
            desc = (p.get("description") or "").replace("|", "\\|").replace("\n", " ")
            lines.append(f"| `{arg}` | {typ} | {default} | {desc} |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("references/scripts.md is out of date: run python3 scripts/_docs.py", file=sys.stderr)
            sys.exit(1)
        print("references/scripts.md is up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
